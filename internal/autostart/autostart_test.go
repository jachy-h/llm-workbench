func TestSupportedMatchesRuntime(t *testing.T) {
	if got, want := Supported(), runtime.GOOS == "darwin"; got != want {
		t.Errorf("Supported() = %v, want %v", got, want)
	}
}

func TestPlistPath(t *testing.T) {
	path := PlistPath()
	if !strings.HasSuffix(path, filepath.Join("Library", "LaunchAgents", Label+".plist")) {
		t.Errorf("PlistPath = %q", path)
	}
	if !filepath.IsAbs(path) {
		t.Errorf("PlistPath is not absolute: %q", path)
	}
}

func TestStateShape(t *testing.T) {
	state := StateNow()
	if state.Label != Label {
		t.Errorf("Label = %q", state.Label)
	}
	if state.PlistPath != PlistPath() {
		t.Errorf("PlistPath = %q, want %q", state.PlistPath, PlistPath())
	}
	if state.Supported != (runtime.GOOS == "darwin") {
		t.Errorf("Supported = %v", state.Supported)
	}
	if state.Supported {
		return // do not assert install state on a real macOS box
	}
	if state.Installed || state.Loaded {
		t.Errorf("non-darwin state = %+v", state)
	}
}

func TestRenderPlist(t *testing.T) {
	command := []string{
		"/Users/me/Library/Application Support/llm-workbench/llm-workbench",
		"--port", "11500",
		"--foreground",
		"--no-browser",
	}
	payload := RenderPlist(command, "/tmp/proxy log.txt", "/Users/me/work")
	for _, needle := range []string{
		`<?xml version="1.0" encoding="UTF-8"?>`,
		`<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"`,
		"<key>Label</key>",
		"<string>" + Label + "</string>",
		"<key>ProgramArguments</key>",
		"<key>RunAtLoad</key>",
		"<key>KeepAlive</key>",
		"<key>ThrottleInterval</key>",
		"<integer>10</integer>",
		"<key>StandardOutPath</key>",
		"<key>StandardErrorPath</key>",
		"<string>/tmp/proxy log.txt</string>",
		"<key>WorkingDirectory</key>",
		"<string>/Users/me/work</string>",
	} {
		if !strings.Contains(payload, needle) {
			t.Errorf("plist missing %q", needle)
		}
	}
	for _, arg := range command {
		if !strings.Contains(payload, "<string>"+arg+"</string>") {
			t.Errorf("plist missing argument %q", arg)
		}
	}

	// It must be well-formed XML.
	decoder := xml.NewDecoder(strings.NewReader(payload))
	for {
		if _, err := decoder.Token(); err != nil {
			if err == io.EOF {
				break
			}
			t.Fatalf("plist is not valid XML: %v", err)
		}
	}
}

func TestRenderPlistOmitsWorkingDirectoryWhenEmpty(t *testing.T) {
	payload := RenderPlist([]string{"/bin/true"}, "/tmp/a.log", "")
	if strings.Contains(payload, "WorkingDirectory") {
		t.Error("WorkingDirectory should be omitted when empty")
	}
}

func TestRenderPlistEscapesXML(t *testing.T) {
	payload := RenderPlist([]string{"/bin/echo", "a&b<c>d\"e"}, "/tmp/x&y.log", "/tmp/w<d")
	if strings.Contains(payload, "a&b") {
		t.Error("raw & was not XML-escaped")
	}
	if !strings.Contains(payload, "a&amp;b&lt;c&gt;d&#34;e") {
		t.Errorf("escaped argument missing:\n%s", payload)
	}
	decoder := xml.NewDecoder(strings.NewReader(payload))
	for {
		if _, err := decoder.Token(); err != nil {
			if err == io.EOF {
				break
			}
			t.Fatalf("escaped plist is not valid XML: %v", err)
		}
	}
}

func TestPlistPathUnderHome(t *testing.T) {
	home, err := os.UserHomeDir()
	if err != nil {
		t.Skip("no home directory")
	}
	if !strings.HasPrefix(PlistPath(), home) {
		t.Errorf("PlistPath %q is not under %q", PlistPath(), home)
	}
}

func TestParseJobPID(t *testing.T) {
	running := `gui/501/com.github.llm-workbench = {
	active count = 1
	path = /Users/x/Library/LaunchAgents/com.github.llm-workbench.plist
	state = running

	program = /Users/x/bin/llm-workbench
	pid = 4321
	immediate reason = speculative
}`
	if pid, ok := parseJobPID(running); !ok || pid != 4321 {
		t.Errorf("parseJobPID(running) = %d, %v; want 4321, true", pid, ok)
	}

	for name, output := range map[string]string{
		"no pid line": "state = not running\n\tactive count = 0",
		"zero pid":    "state = not running\n\tpid = 0\n",
		"garbage pid": "\tpid = abc\n",
		"empty":       "",
	} {
		if pid, ok := parseJobPID(output); ok {
			t.Errorf("parseJobPID(%s) = %d, true; want not found", name, pid)
		}
	}
}

// TestRenderPlistLanguage pins the language of the supervised instance: launchd
// does not inherit the shell locale, so LLM_WORKBENCH_LANG has to be in the plist.
func TestRenderPlistLanguage(t *testing.T) {
	t.Cleanup(func() { i18n.Set(i18n.ZH) })

	i18n.Set(i18n.EN)
	payload := RenderPlist([]string{"/bin/true"}, "/tmp/a.log", "")
	for _, needle := range []string{
		"<key>EnvironmentVariables</key>",
		"<key>LLM_WORKBENCH_LANG</key>",
		"<string>en</string>",
		"Generated by llm-workbench",
	} {
		if !strings.Contains(payload, needle) {
			t.Errorf("English plist missing %q:\n%s", needle, payload)
		}
	}
	if strings.Contains(payload, "由 llm-workbench 生成") {
		t.Error("English plist still has the Chinese comment")
	}

	i18n.Set(i18n.ZH)
	payload = RenderPlist([]string{"/bin/true"}, "/tmp/a.log", "")
	if !strings.Contains(payload, "<string>zh</string>") || !strings.Contains(payload, "由 llm-workbench 生成") {
		t.Errorf("Chinese plist is not localized:\n%s", payload)
	}

	decoder := xml.NewDecoder(strings.NewReader(payload))
	for {
		if _, err := decoder.Token(); err != nil {
			if err == io.EOF {
				break
			}
			t.Fatalf("localized plist is not valid XML: %v", err)
		}
	}
}

// TestCommentCannotBreakThePlist covers the one XML hazard in a comment.
func TestCommentCannotBreakThePlist(t *testing.T) {
	got := comment("a -- b---c-")
	if strings.Contains(strings.TrimSuffix(strings.TrimPrefix(got, "<!-- "), " -->\n"), "--") {
		t.Errorf("comment still contains %q", "--")
	}
	if !strings.HasPrefix(got, "<!-- ") || !strings.HasSuffix(got, " -->\n") {
		t.Errorf("comment = %q", got)
	}
}
